import { common, missionBlock, toJson as j } from './prompts.js';
import { criteriaBlock } from './criteria.js';

const card = (c) => ({ id: c.id, 제목: c.title, 컨셉: c.concept, 보이는_표현: c.visual, 사용자가_얻는_것: c.gain });

/** 문제를 다시 정의한다 — 브리프가 묻는 대로 답하면 기본안이 나온다 */
export function reframePrompt(project, baseline, count = 3, note = '') {
  return {
    system: `${common(project)}

## 너의 역할 — 문제 다시 정의
브리프가 묻는 그대로 답하면 아래 기본안이 나온다. 기본안은 틀린 안이 아니라 누구나 내는 안이다.
이 과제를 **다르게 정의**하는 문제 정의 ${count}개를 낸다. 답이 아니라 질문을 바꾼다.

## 규칙
- 먼저 근본 이슈가 브리프의 목적 전체와 성공 기준을 덮는지 본다. 덮지 못하는 부분이 있으면 \`gap\`에 한 문장으로 쓴다. 없으면 빈 문자열이다.
- 각 정의는 "누구의 무엇이 문제인가" 한 문장이다. 브리프의 정의와 무엇이 다른지 쓴다.
- 문제 정의는 근본 이슈 안에서만 내지 않는다. \`gap\`이 있으면 적어도 하나는 그 부분을 겨눈다.
- 브리프에 성공 기준이 있으면 적어도 하나는 성공 기준이 재는 행동(누가 얼마나 자주 무엇을 하는가)을 직접 겨누고 \`success\`를 true로 둔다. 해법을 미리 정한 문장으로 쓰지 않는다.
- ${count}개는 서로 다른 방향이어야 한다. 적어도 하나는 브리프의 전제(타겟 · 핵심 순간 · 문제라고 적힌 것) 하나를 의심한다.
- 팩트북에 브리프의 전제와 어긋나는 사실이 있으면 거기서 출발한다. 팩트 id를 적는다.
- 더프롬의 관점에서 본다 — 익숙한 것을 다시 보게 할 자리가 어디인가.
- 브리프의 제약(지킬 것 · 금지)은 넘지 않는다. 부딪히는 요구가 있으면 \`risk\`에 적는다.

## 출력 JSON
{ "gap": "근본 이슈가 덮지 못하는 목적 · 성공 기준 (없으면 빈 문자열)", "frames": [ { "frame": "누구의 무엇이 문제인가", "why": "브리프의 정의와 다른 점", "success": false, "risk": "부딪히는 요구 (없으면 빈 문자열)", "facts": ["팩트 id"] } ] }`,
    user: `${missionBlock(project)}

## 브리프대로 답한 기본안
${j(baseline?.concepts || [])}

${note ? `${note}\n\n` : ''}문제 정의를 JSON으로 출력하라.`,
  };
}

/** 충돌 교배 — 부딪히는 두 안을 하나도 버리지 않고 새 안으로 만든다 */
export function crossPrompt(project, a, b, why, baseline) {
  return {
    system: `${common(project)}

## 너의 역할 — 충돌 교배
서로 부딪히는 두 안이 주어진다. 좋은 안은 충돌을 푸는 자리에서 나온다.
둘 중 하나를 고르거나 반씩 섞지 않는다. **두 안이 각자 지키려는 것을 둘 다 살리는 세 번째 안**을 낸다.

## 규칙
- 먼저 두 안이 각각 무엇을 지키려 하는지 한 문장씩 쓴다(\`keeps\`).
- 새 안은 두 안 어느 쪽에도 없던 장치 하나를 가져야 한다. 그 장치가 충돌을 어떻게 푸는지 \`how\`에 쓴다.
- 기본안과 같은 해법으로 돌아가면 실패다.
- \`visual\`은 화면이나 현장에서 실제로 보이는 모습이다. \`gain\`은 누가 언제 무엇을 얻는지다.

## 출력 JSON
{ "keeps": { "a": "", "b": "" }, "title": "제목 — 수단 + 효과", "concept": "컨셉 한두 문장", "visual": "보이는 표현", "gain": "사용자가 얻는 것", "how": "충돌을 푸는 장치" }`,
    user: `${missionBlock(project)}

## 안 A
${j(card(a))}

## 안 B
${j(card(b))}

## 두 안이 부딪히는 이유
${why}

## 기본안 (이 해법으로 돌아가지 않는다)
${j((baseline?.concepts || []).map((c) => ({ id: c.id, 컨셉: c.concept })))}

교배한 안을 JSON으로 출력하라.`,
  };
}

/** 기본안 대조 — 기본안과 같은 해법은 탈락시킨다 */
export function screenPrompt(project, candidates, baseline) {
  return {
    system: `${common(project)}

## 너의 역할 — 기본안 대조
후보 ${candidates.length}개를 기본안과 비교한다. 기본안은 더프롬의 관점 없이 브리프만 읽고 낸 안이다.

## 규칙
- 후보마다 가장 가까운 기본안을 고르고 판정한다: "같음"(표현만 다르고 해법이 같다) · "일부"(같은 해법에 새 장치를 더했다) · "다름"(기본안에 없는 해법이다).
- 후보의 설명이 아니라 실제로 사용자에게 달라지는 것을 비교한다. 말만 바꾼 안은 "같음"이다.
- 관대하게 보지 않는다. 판단이 어려우면 더 가까운 쪽("같음" 또는 "일부")으로 판정한다.
- \`family\`: 후보끼리도 견준다. 핵심 해법이 같은 후보에는 같은 묶음 이름(짧은 한 구절)을 붙인다. 표현만 다른 변형은 같은 묶음이다.
- \`empty\`: 사용자가 얻는 것이 비어 있으면 true. 다르기만 한 안이다.
- \`success\`: 브리프의 성공 기준이 재는 행동과 빈도에 이 안이 닿는 정도 — "직접"(이 안이 그 행동을 그 빈도로 만든다) · "간접"(일부 고객이나 드문 순간에만 닿는다) · "없음". 성공 기준이 브리프에 없으면 빈 문자열. 탈락 사유가 아니라 결선 자리를 정할 때 쓴다.
- \`breaks\`: 브리프의 제약을 넘는 곳이 있으면 한 문장. 없으면 빈 문자열. 제약을 넘는 것은 탈락 사유가 아니라 뒤에서 고칠 대상이다.

## 출력 JSON
{ "screens": [ { "id": "K1", "nearest": "B1", "verdict": "같음|일부|다름", "why": "한 문장", "family": "해법 묶음 이름", "empty": false, "success": "직접|간접|없음", "breaks": "" } ] }`,
    user: `${missionBlock(project)}

## 기본안
${j(baseline?.concepts || [])}

## 후보
${j(candidates.map(card))}

판정을 JSON으로 출력하라.`,
  };
}

/** 1:1 대결 — 더프롬이 내보낼 안은 어느 쪽인가 */
export function duelPrompt(project, pairs) {
  return {
    system: `${common(project)}

${criteriaBlock()}

## 너의 역할 — 1:1 대결 판정
두 안씩 짝지은 대결 ${pairs.length}건이 주어진다. 대결마다 **더프롬의 이름으로 클라이언트에게 내보낼 안**을 하나 고른다.
어느 안이 어떤 과정으로 만들어졌는지는 알려 주지 않는다. 글의 길이나 말투로 고르지 않는다.

## 규칙
- 차별화와 실효성 두 기준으로 견준다. 점수를 매기지 않고 두 안을 직접 비교한다. 약점이 없는 안이 아니라 **더 멀리 가는 안**을 고른다 — 한쪽이 무난하고 다른 쪽이 뚜렷한 차별화를 가졌으면, 뚜렷한 쪽의 약점이 고칠 수 있는 것인 한 뚜렷한 쪽이 이긴다.
- 실효성에서는 성공 기준을 먼저 본다. 한쪽만 성공 기준이 재는 행동에 직접 닿으면, 다른 쪽의 차별화가 뚜렷이 앞서지 않는 한 닿는 쪽이 이긴다. 닿지 않는 것이 고칠 수 있는 약점이면 그 사실을 이유에 적는다.
- 다르기만 하고 사람이 얻는 것이 없는 안은 진다. 구현 조건이 걸리는 것만으로는 지지 않는다(뒤에서 고친다).
- \`notable\`: 이겼든 졌든, 한 가지가 뚜렷하게 뛰어난 안이 있으면 그 id와 무엇이 뛰어난지. 없으면 빈 문자열.
- 글만으로 가릴 수 없으면 그래도 한쪽을 고르되 \`unsure\`를 true로 둔다.
- 비기지 않는다. 이긴 이유를 진 안과 비교해 한 문장으로 쓴다.

## 출력 JSON
{ "duels": [ { "pair": "D1", "winner": "후보 id", "why": "한 문장", "notable": "", "notable_why": "", "unsure": false } ] }`,
    user: `${missionBlock(project)}

## 대결
${j(pairs.map((p) => ({ pair: p.id, 안_1: card(p.a), 안_2: card(p.b) })))}

대결 판정을 JSON으로 출력하라.`,
  };
}

/** 같은 해법 묶기 — 결선에 오른 안끼리 다시 견준다. 최종안은 서로 다른 해법이어야 한다 */
export function distinctPrompt(project, cands) {
  return {
    system: `${common(project)}

## 너의 역할 — 같은 해법 묶기
결선에 오른 안과 예비 안 ${cands.length}개를 서로 견주어, 핵심 해법이 같은 안끼리 묶는다. 최종안으로 같은 해법이 두 번 나가지 않게 하려는 것이다.

## 규칙
- 제목이나 설명의 말이 아니라 **사용자가 실제로 하게 되는 행동과 그 행동이 일어나는 순간**을 견준다.
- 클라이언트가 두 안을 받았을 때 "같은 안의 두 버전"으로 읽으면 같은 묶음이다. 접점이나 화면 배치만 다른 안, 한 안이 다른 안의 일부인 안은 같은 묶음이다.
- 판단이 어려우면 묶는다. 관대하게 나누지 않는다.
- 모든 안을 빠짐없이 한 묶음에 넣는다. 혼자인 안은 1개짜리 묶음이다.
- 묶음마다 그 해법을 한 구절로 이름 붙이고, 같은 묶음으로 본 이유를 한 문장으로 쓴다(1개짜리 묶음은 빈 문자열).

## 출력 JSON
{ "groups": [ { "name": "해법 한 구절", "ids": ["K1", "K4"], "why": "" } ] }`,
    user: `${missionBlock(project)}

## 안
${j(cands.map(card))}

묶음을 JSON으로 출력하라.`,
  };
}

/** 공격 — 뽑힌 안의 약점을 찾는다. 고르는 단계가 아니라 단련하는 단계다 */
export function attackPrompt(project, cand, baseline) {
  return {
    system: `${common(project)}

## 너의 역할 — 공격
아래 안은 경쟁에서 이긴 안이다. 내보내기 전에 약점을 찾는다. 안을 떨어뜨리려는 것이 아니라 고칠 곳을 정확히 짚는 것이다.

## 공격하는 쪽
- 성공 기준: 이 안이 만드는 행동과 빈도가 브리프의 성공 기준이 재는 행동과 빈도에 못 미치는 곳. 얼마나 못 미치는지 쓴다
- 제약: 브리프의 지킬 것 · 금지 · 플랫폼 조건을 넘는 곳
- 타겟 · 사용 습관: 실제 사용 상황(시간 · 장소 · 기기)에서 쓰이지 않을 곳. 팩트북에 근거가 있으면 팩트 id를 적는다
- 관성: 사람들이 몸으로 아는 구조를 깨뜨리는 곳
- 노랑: 이 안 때문에 못 쓰게 되는 사람
- 사람이 얻는 것: 다르기만 하고 얻는 것이 없는 곳
- 기본안: 구현하다 보면 결국 기본안으로 돌아갈 곳
- 문(N7): 더프롬 자사의 형상 · 색 · 서사가 결과물에 들어간 곳

## 규칙
- 약점마다 어디가 왜 문제인지 구체적으로 쓴다. 일반론("사용성 검증이 필요하다")은 쓰지 않는다.
- \`severity\`: 3(이대로는 내보낼 수 없다) · 2(고쳐야 한다) · 1(다듬으면 좋다). 약점이 없는 쪽은 적지 않는다.
- \`keep\`: 고치더라도 반드시 지켜야 할 이 안의 대담한 부분 한 문장.

## 출력 JSON
{ "attacks": [ { "from": "성공 기준|제약|타겟 · 사용 습관|관성|노랑|사람이 얻는 것|기본안|문(N7)", "hit": "어디가 왜 문제인가", "severity": 1, "facts": ["팩트 id"] } ], "keep": "지켜야 할 대담한 부분" }`,
    user: `${missionBlock(project)}

## 공격할 안
${j(card(cand))}

## 기본안
${j((baseline?.concepts || []).map((c) => ({ id: c.id, 컨셉: c.concept })))}

공격을 JSON으로 출력하라.`,
  };
}

/** 보완 — 대담한 부분은 지키고 공격받은 곳만 고친다 */
export function revisePrompt(project, cand, attack, baseline, others = []) {
  return {
    system: `${common(project)}

## 너의 역할 — 보완
경쟁에서 이긴 안과 그 안이 받은 공격이 주어진다. 공격받은 곳을 고친다.

## 규칙
- "지켜야 할 대담한 부분"은 그대로 둔다. 안전하게 만들려고 깎지 않는다.
- 심각도 2 이상의 공격은 모두 고친다. "성공 기준" 공격은 설명을 덧붙여 넘기지 않는다. 성공 기준이 재는 행동을 실제로 만드는 장치를 넣어 고친다. 고칠 수 없으면 왜 그런지와 사람이 정할 것을 \`open\`에 적는다.
- 고친 결과가 기본안과 같은 해법이 되면 실패다. 그 경우 고치지 말고 \`open\`에 남긴다.
- 다른 최종안이 주어지면, 그 안의 핵심 장치를 가져다 쓰지 않는다. 이 안의 해법 안에서 고친다. 고친 결과가 다른 최종안과 같은 해법이 되면 실패다.
- 실현 조건은 탈락 사유가 아니라 고칠 대상이다. 안을 버리지 않고 조건에 맞춘다.
- 고친 뒤에도 짧아야 한다. \`concept\`은 두 문장 이내, \`visual\`은 네 문장 이내로 쓴다. 고친 세부 사항은 \`fixed\`에만 적고 본문에 덧붙이지 않는다. 한두 문장으로 말할 수 없게 된 안은 고친 것이 아니라 흐려진 것이다.
- \`keep\`(지킬 관성)과 \`change\`(바꿀 해석)를 가른다. \`verdict\`에는 근본 이슈의 판정 질문에 넣은 결과를 쓴다.

## 출력 JSON
{ "title": "제목 — 수단 + 효과", "concept": "컨셉 한두 문장", "visual": "보이는 표현", "gain": "사용자가 얻는 것", "keep": "지킬 관성", "change": "바꿀 해석", "verdict": "판정 질문에 넣은 결과",
  "fixed": [ { "hit": "받은 공격", "fix": "고친 것" } ], "open": ["사람이 정할 것"] }`,
    user: `${missionBlock(project)}

## 이긴 안
${j(card(cand))}

## 받은 공격
${j(attack.attacks)}

## 지켜야 할 대담한 부분
${attack.keep}

## 기본안 (이 해법으로 돌아가지 않는다)
${j((baseline?.concepts || []).map((c) => ({ id: c.id, 컨셉: c.concept })))}
${others.length ? `\n## 다른 최종안 (이 안들의 핵심 장치를 가져다 쓰지 않는다)\n${j(others.map((o) => ({ 제목: o.title, 컨셉: o.concept })))}\n` : ''}
보완한 안을 JSON으로 출력하라.`,
  };
}
