/** 프롬프트에 넣을 글 */
export function depthBlock(id) {
  const d = ISM_DEPTH[id];
  if (!d) return '';
  return `- 시대 조건: ${d.era}
- 던진 질문: ${d.question}
- 사조 안의 갈래
${d.strands.map((s) => `  - ${s.name}: ${s.how}`).join('\n')}
- 내부 모순: ${d.paradox}
- 후대의 변용: ${d.after}`;
}
